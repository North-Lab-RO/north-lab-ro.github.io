/** Path of the same page in another language. EN lives at the root, RO under /ro/. */
export function altPath(path: string, to: Lang): string {
  const bare = path.replace(/^\/ro(?=\/|$)/, '') || '/';
  return to === 'ro' ? `/ro${bare === '/' ? '/' : bare}` : bare;
}

